"""Head pose (yaw / pitch / roll) from Face Mesh 2D landmarks via OpenCV solvePnP (V10).

A small set of Face Mesh points (nose tip, chin, outer/inner eye corners, mouth
corners) is matched against a generic 3D face model (constant canonical coords in
millimetres). ``cv2.solvePnP`` recovers the head rotation; the camera intrinsics
are a frame-size-based approximation (no real calibration). Because the focal
length and the 3D model are approximate, **absolute angles are not accurate** —
only relative changes (vs the calibrated frontal pose) are meaningful. The engine
subtracts the calibration baseline and reports the delta (see CONTRACTS §1).

Pure NumPy + cv2 geometry on landmark coordinates — no image, no inference here.

Sign convention (CONTRACTS, user's own-view; the web mirrors for display):
    yaw_deg  > 0  user turns head to THEIR right
    pitch_deg> 0  chin tucked down (looking down)
    roll_deg > 0  head tilted toward the user's right shoulder
``estimate_head_pose`` returns RAW camera-frame Euler angles already mapped to
these signs; the engine turns them into baseline-relative deltas.
"""
from __future__ import annotations

import cv2
import numpy as np

from nunchi.vision import metrics as M

# Generic 3D face model (millimetres), centred near the nose/sellion. Values are a
# widely used canonical head approximation (nose at origin); FaceMesh indices map
# to each point. Absolute scale is irrelevant to the recovered rotation.
# Axes here are: +X right (subject's left in the image), +Y up, +Z toward camera.
_MODEL_3D = {
    M.NOSE_TIP: (0.0, 0.0, 0.0),            # nose tip
    M.CHIN: (0.0, -63.6, -12.5),            # chin
    M.LEFT_EYE["outer"]: (-43.3, 32.7, -26.0),   # left eye outer corner
    M.RIGHT_EYE["outer"]: (43.3, 32.7, -26.0),   # right eye outer corner
    M.MOUTH["left"]: (-28.9, -28.9, -24.1),      # left mouth corner
    M.MOUTH["right"]: (28.9, -28.9, -24.1),      # right mouth corner
}
# Fewer points = cheaper solvePnP (latency budget). Order is fixed for the arrays.
_MODEL_IDX = list(_MODEL_3D.keys())
_MODEL_PTS = np.array([_MODEL_3D[i] for i in _MODEL_IDX], dtype=np.float64)


def _camera_matrix(w: int, h: int) -> np.ndarray:
    """Approximate pinhole intrinsics from frame size (focal ~= width, centre = mid)."""
    f = float(w)
    cx, cy = w / 2.0, h / 2.0
    return np.array([[f, 0.0, cx], [0.0, f, cy], [0.0, 0.0, 1.0]], dtype=np.float64)


def _rot_to_euler(rmat: np.ndarray) -> tuple[float, float, float]:
    """Rotation matrix -> (yaw, pitch, roll) in degrees, camera frame.

    Uses the standard Tait-Bryan decomposition. Returns angles before the
    CONTRACTS sign mapping (that mapping is applied in ``estimate_head_pose``).
    """
    sy = float(np.sqrt(rmat[0, 0] ** 2 + rmat[1, 0] ** 2))
    if sy > 1e-6:
        x = np.arctan2(rmat[2, 1], rmat[2, 2])   # pitch (about camera X)
        y = np.arctan2(-rmat[2, 0], sy)          # yaw   (about camera Y)
        z = np.arctan2(rmat[1, 0], rmat[0, 0])   # roll  (about camera Z)
    else:  # gimbal-lock fallback
        x = np.arctan2(-rmat[1, 2], rmat[1, 1])
        y = np.arctan2(-rmat[2, 0], sy)
        z = 0.0
    return float(np.degrees(x)), float(np.degrees(y)), float(np.degrees(z))


def estimate_head_pose(
    pts: np.ndarray, frame_w: int, frame_h: int
) -> tuple[float, float, float, float] | None:
    """Estimate (yaw_deg, pitch_deg, roll_deg, reproj_err_px) from landmarks.

    ``pts`` is the (478,2) Face Mesh array in full-frame pixels. Returns None if
    the solve fails or inputs are degenerate. Angles follow the CONTRACTS signs
    (raw camera-frame angles; the engine subtracts the calibration baseline).
    ``reproj_err_px`` is the mean reprojection error used for the confidence.
    """
    if pts is None or frame_w <= 0 or frame_h <= 0:
        return None
    try:
        image_pts = np.array([pts[i] for i in _MODEL_IDX], dtype=np.float64)
    except (IndexError, TypeError):
        return None
    if image_pts.shape != (_MODEL_PTS.shape[0], 2) or not np.all(np.isfinite(image_pts)):
        return None

    cam = _camera_matrix(frame_w, frame_h)
    dist = np.zeros((4, 1), dtype=np.float64)   # assume no lens distortion
    try:
        ok, rvec, tvec = cv2.solvePnP(
            _MODEL_PTS, image_pts, cam, dist, flags=cv2.SOLVEPNP_ITERATIVE
        )
    except cv2.error:
        return None
    if not ok:
        return None

    rmat, _ = cv2.Rodrigues(rvec)
    pitch_cam, yaw_cam, roll_cam = _rot_to_euler(rmat)

    # Map camera-frame Euler angles to the CONTRACTS own-view signs. The 3D model
    # faces the camera with +X = subject's right, +Y = up, +Z = toward camera, and
    # image Y points DOWN. This mapping is pinned by the synthetic-rotation test
    # (tests/vision/test_headpose.py): landmarks are generated by rotating the 3D
    # model with the physical motion each CONTRACTS sign means and the test asserts
    # the recovered angle has that sign and magnitude:
    #   yaw   > 0  user turns to their right  (model +Y rotation)  => +yaw_cam
    #   pitch > 0  chin tucked down (look down)(model +X rotation)  => +pitch_cam
    #   roll  > 0  tilt to user's right shoulder(model +Z rotation)=> +roll_cam
    yaw = yaw_cam
    pitch = pitch_cam
    roll = roll_cam

    # reprojection error (confidence basis)
    proj, _ = cv2.projectPoints(_MODEL_PTS, rvec, tvec, cam, dist)
    proj = proj.reshape(-1, 2)
    reproj_err = float(np.mean(np.linalg.norm(proj - image_pts, axis=1)))
    return (round(yaw, 2), round(pitch, 2), round(roll, 2), round(reproj_err, 3))


def reproj_to_conf(reproj_err_px: float, face_px: float) -> float:
    """Map mean reprojection error (px) to a 0..1 confidence.

    Normalised by face height so the same relative error gives the same
    confidence at any distance. err ~= 0 -> conf 1; err ~= 8% of face height -> ~0.
    """
    if face_px <= 0:
        return 0.0
    rel = reproj_err_px / float(face_px)
    conf = 1.0 - rel / 0.08
    return float(max(0.0, min(1.0, conf)))


def head_pose_from_landmarks(
    pts: np.ndarray, frame_w: int, frame_h: int, face_px: float
) -> dict[str, float] | None:
    """Combined per-frame head pose for ``overlay.pose`` (raw, pre-baseline).

    yaw/pitch come from ``solvePnP`` (stable enough with 6 points); roll comes from
    the eye-line metric (``head_roll_deg``) because PnP roll is noise-sensitive
    with so few points (see test_headpose). ``conf`` is the reprojection-error
    confidence. Returns None when the solve fails. The engine subtracts the
    calibration baseline and smooths these; absolute accuracy is not claimed.
    """
    est = estimate_head_pose(pts, frame_w, frame_h)
    if est is None:
        return None
    yaw, pitch, _pnp_roll, reproj = est
    roll = M.head_roll_deg(pts)   # eye-line roll: tilt to user's right -> >0 (CONTRACTS)
    return {
        "yaw_deg": round(yaw, 2),
        "pitch_deg": round(pitch, 2),
        "roll_deg": round(roll, 2),
        "reproj_err": round(reproj, 3),
        "conf": round(reproj_to_conf(reproj, face_px), 3),
    }
